    `author_name` VARCHAR(255) NOT NULL,
    `intro_text` TEXT,
    `source_id` VARCHAR(64),
    PRIMARY KEY (`author_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

