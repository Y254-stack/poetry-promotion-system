-- 更新唐代作者
UPDATE `author` a
INNER JOIN `tmp_author_intro_tang` t
    ON a.`canonical_name` = t.`author_name`
    AND a.`dynasty_name` = '唐代'
SET
    a.`intro_text` = t.`intro_text`,
    a.`source_id` = t.`source_id`
WHERE a.`intro_text` IS NULL;

-- 更新宋代作者
UPDATE `author` a
INNER JOIN `tmp_author_intro_song` t
    ON a.`canonical_name` = t.`author_name`
    AND a.`dynasty_name` = '宋代'
