-- =========================================================
-- import_author_intro.sql
-- 导入作者简介数据
--
-- 功能：
-- 1. 修改 author 表结构，添加简介字段
-- 2. 从 JSON 文件导入唐代和宋代作者简介
--
-- 前置条件：
-- 1. 已经执行过 poetry_full_init.sql，author 表已存在
-- 2. MySQL 8.0+
--
-- 执行方式：
-- mysql -u root -p poetry_clean < sql/import_author_intro.sql
-- =========================================================

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

USE `poetry_clean`;

-- =========================================================
-- 步骤1：修改 author 表结构，添加简介字段
-- =========================================================

-- 检查并添加 intro_text 字段
SET @col_exists = 0;
SELECT COUNT(*) INTO @col_exists
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = 'poetry_clean'
  AND TABLE_NAME = 'author'
  AND COLUMN_NAME = 'intro_text';

SET @sql = IF(@col_exists = 0,
    'ALTER TABLE `author` ADD COLUMN `intro_text` TEXT DEFAULT NULL COMMENT ''作者简介/生平''',
    'SELECT ''Column intro_text already exists'' AS message');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- 检查并添加 source_id 字段
SET @col_exists = 0;
SELECT COUNT(*) INTO @col_exists
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = 'poetry_clean'
  AND TABLE_NAME = 'author'
  AND COLUMN_NAME = 'source_id';

SET @sql = IF(@col_exists = 0,
    'ALTER TABLE `author` ADD COLUMN `source_id` VARCHAR(64) DEFAULT NULL COMMENT ''来源数据的ID''',
    'SELECT ''Column source_id already exists'' AS message');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- 检查并添加索引
SET @index_exists = 0;
SELECT COUNT(*) INTO @index_exists
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = 'poetry_clean'
  AND TABLE_NAME = 'author'
  AND INDEX_NAME = 'idx_author_source_id';

SET @sql = IF(@index_exists = 0,
    'ALTER TABLE `author` ADD INDEX `idx_author_source_id` (`source_id`)',
    'SELECT ''Index idx_author_source_id already exists'' AS message');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- =========================================================
-- 步骤2：创建临时表，用于存储 JSON 数据
