SELECT
    COUNT(*) AS total_authors,
    SUM(CASE WHEN intro_text IS NOT NULL THEN 1 ELSE 0 END) AS authors_with_intro,
    SUM(CASE WHEN intro_text IS NULL THEN 1 ELSE 0 END) AS authors_without_intro
FROM `author`;

SELECT
    `dynasty_name`,
    COUNT(*) AS total,
    SUM(CASE WHEN intro_text IS NOT NULL THEN 1 ELSE 0 END) AS with_intro
FROM `author`
GROUP BY `dynasty_name`
ORDER BY total DESC;

