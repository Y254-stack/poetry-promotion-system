DROP TEMPORARY TABLE IF EXISTS `tmp_author_intro_tang`;
CREATE TEMPORARY TABLE `tmp_author_intro_tang` (
    `author_name` VARCHAR(255) NOT NULL,
    `intro_text` TEXT,
    `source_id` VARCHAR(64),
    PRIMARY KEY (`author_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

DROP TEMPORARY TABLE IF EXISTS `tmp_author_intro_song`;
